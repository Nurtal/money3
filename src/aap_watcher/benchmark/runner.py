"""Benchmark runner.

Runs every extractor over a gold corpus and produces comparable, actually
measured results: field-level metrics, latency (ms/doc), memory (MB) and cost
(€/doc). Results are generated by execution — never hard-coded.
"""

from __future__ import annotations

import time
import tracemalloc
from dataclasses import dataclass, field

from ..extraction.base import Document
from .metrics import _COMPARED_FIELDS, ExtractorResult, evaluate_extractor

_METRIC_FIELDS = _COMPARED_FIELDS


@dataclass
class BenchmarkResult:
    results: list[ExtractorResult] = field(default_factory=list)
    n_examples: int = 0


def _prediction_dict(extraction) -> dict:
    dump = extraction.model_dump()
    return {f: dump.get(f) for f in _METRIC_FIELDS}


def run_benchmark(
    examples,
    extractors,
    track_latency: bool = True,
    track_memory: bool = True,
    track_cost: bool = True,
) -> BenchmarkResult:
    result = BenchmarkResult(n_examples=len(examples))
    for extractor in extractors:
        predictions: list[dict] = []
        golds: list[dict] = []
        lat_total = 0.0
        mem_peak = 0.0
        if track_memory:
            tracemalloc.start()
        for ex in examples:
            doc = Document(text=ex.text, source_url=ex.source_url)
            t0 = time.perf_counter()
            extraction = extractor.extract(doc)
            if track_latency:
                lat_total += (time.perf_counter() - t0) * 1000.0
            predictions.append(_prediction_dict(extraction))
            golds.append(ex.expected)
        if track_memory:
            _, peak = tracemalloc.get_traced_memory()
            mem_peak = peak / (1024 * 1024)
            tracemalloc.stop()

        er = evaluate_extractor(getattr(extractor, "name", type(extractor).__name__), predictions, golds)
        er.latency_ms = lat_total / len(examples) if examples else 0.0
        er.memory_mb = mem_peak
        if track_cost:
            cost = getattr(extractor, "cost_per_doc", 0.0) or 0.0
            er.cost_eur = cost * len(examples)
        result.results.append(er)
    return result
